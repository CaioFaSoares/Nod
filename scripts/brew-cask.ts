#!/usr/bin/env bun
// Writes `Casks/nod.rb`, the Homebrew cask of the macOS builds, from a release's `manifest.json`
// (`docs/distribuicao.md` §3.1). The tap is this repository itself:
//
//   brew tap caiofasoares/nod https://github.com/CaioFaSoares/Nod
//   brew install --cask nod
//
// Usage:
//   bun scripts/brew-cask.ts <manifest.json> [--repo owner/name] [--out Casks/nod.rb]
//
// `release.yml` runs it after publishing, so the cask always names the latest release with the
// sha256 the manifest carries for each macOS zip — Apple silicon is the Electrobun build, Intel the
// tinyjs one (`docs/canonico.md` §22). A manifest older than the cask on disk is refused with exit 0
// and nothing written: re-running the release of an old version never moves the cask backwards.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { compareVersions } from '../shared/version';

export const CASK_PATH = 'Casks/nod.rb';
const DEFAULT_REPO = 'CaioFaSoares/Nod';
const SHA256 = /^[0-9a-f]{64}$/;

export interface CaskInput {
  version: string;
  repo: string;
  arm64Sha: string;
  x86Sha: string;
}

/** What the cask needs out of a merged `manifest.json`, or the reason it cannot be read. */
export function caskInputFrom(manifest: unknown, repo: string): CaskInput | string {
  if (typeof manifest !== 'object' || manifest === null) return 'the manifest is not an object';
  const version = 'version' in manifest ? manifest.version : undefined;
  const mac = 'mac' in manifest ? manifest.mac : undefined;
  if (typeof version !== 'string' || version.trim() === '') return 'the manifest has no version';
  if (typeof mac !== 'object' || mac === null) return 'the manifest has no mac block';
  const sha = (entry: unknown): string | null => {
    if (typeof entry !== 'object' || entry === null || !('sha256' in entry)) return null;
    const value = entry.sha256;
    return typeof value === 'string' && SHA256.test(value) ? value : null;
  };
  const arm64Sha = sha('arm64' in mac ? mac.arm64 : undefined);
  const x86Sha = sha('x86_64' in mac ? mac.x86_64 : undefined);
  if (arm64Sha === null || x86Sha === null) return 'the manifest lacks a sha256 for mac.arm64 or mac.x86_64';
  if (!/^[\w.-]+\/[\w.-]+$/.test(repo)) return `not an owner/name repository: ${repo}`;
  return { version: version.trim(), repo, arm64Sha, x86Sha };
}

/** The version the cask on disk names, or null without one. */
export function caskVersion(source: string): string | null {
  const match = /^\s*version\s+"([^"]+)"/m.exec(source);
  return match === null ? null : match[1];
}

export function caskSource(input: CaskInput): string {
  return `# Generated by scripts/brew-cask.ts from the release manifest; do not edit by hand.
cask "nod" do
  arch arm: "arm64", intel: "x86_64"

  version "${input.version}"
  sha256 arm:   "${input.arm64Sha}",
         intel: "${input.x86Sha}"

  url "https://github.com/${input.repo}/releases/download/release-#{version}/nod-#{version}-macos-#{arch}.zip"
  name "Nod"
  desc "Team's internal tools in one window, logins kept in the system keychain"
  homepage "https://github.com/${input.repo}"

  # Nod installs its own updates (docs/distribuicao.md §8).
  auto_updates true
  # brew audit requires the bundle's own LSMinimumSystemVersion here (the Apple silicon zip says 14);
  # Nod's supported floor is still macOS 15 (docs/canonico.md RNF-01).
  depends_on macos: :sonoma

  app "Nod.app"

  # The builds are signed ad hoc, so Gatekeeper blocks a quarantined copy. Clearing the flag is the
  # release step docs/distribuicao.md §3 documents; it also keeps macOS from translocating the app.
  postflight_steps do
    run "/usr/bin/xattr",
        args:           ["-dr", "com.apple.quarantine", "{{appdir}}/Nod.app"],
        writable_paths: ["Nod.app"],
        writable_base:  :appdir
  end

  zap trash: [
    "~/Library/Application Support/copland.nod",
    "~/Library/Caches/copland.nod",
    "~/Library/HTTPStorages/copland.nod.binarycookies",
    "~/Library/Preferences/copland.nod.plist",
    "~/Library/WebKit/copland.nod",
  ]
end
`;
}

function main(argv: string[]): number {
  const manifestPath = argv.find((value) => !value.startsWith('--'));
  const flag = (name: string): string | undefined =>
    argv.find((value) => value.startsWith(`--${name}=`))?.slice(name.length + 3);
  if (manifestPath === undefined) {
    console.error('usage: bun scripts/brew-cask.ts <manifest.json> [--repo=owner/name] [--out=Casks/nod.rb]');
    return 2;
  }
  const out = flag('out') ?? CASK_PATH;
  const input = caskInputFrom(JSON.parse(readFileSync(manifestPath, 'utf8')), flag('repo') ?? DEFAULT_REPO);
  if (typeof input === 'string') {
    console.error(`brew-cask: ${input}`);
    return 1;
  }
  const current = existsSync(out) ? caskVersion(readFileSync(out, 'utf8')) : null;
  if (current !== null && compareVersions(input.version, current) < 0) {
    console.log(`brew-cask: ${out} already names ${current}, newer than ${input.version}; left as is`);
    return 0;
  }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, caskSource(input));
  console.log(`brew-cask: ${out} → ${input.version} (${input.repo})`);
  return 0;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
